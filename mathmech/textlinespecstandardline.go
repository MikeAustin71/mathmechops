	var ePrefix *ePref.ErrPrefixDto
	var err error

	newStdLine := TextLineSpecStandardLine{}

	ePrefix,
		err = ePref.ErrPrefixDto{}.NewIEmpty(
		errorPrefix,
		"TextLineSpecStandardLine."+
			"NewStdLineMultipleColumns()",
		"")

