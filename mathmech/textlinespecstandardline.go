func (stdLine *TextLineSpecStandardLine) Read(
	p []byte) (
	n int,
	err error) {

	if stdLine.lock == nil {
		stdLine.lock = new(sync.Mutex)
	}

	stdLine.lock.Lock()

	defer stdLine.lock.Unlock()

	ePrefix := ePref.ErrPrefixDto{}.NewEPrefCtx(
		"TextLineSpecStandardLine.Read()",
		"")

	if stdLine.textLineReader == nil {

		strBuilder := strings.Builder{}

		_,
			_,
			err = new(textLineSpecStandardLineMolecule).
			getFormattedText(
				&strBuilder,
				stdLine,
				ePrefix.XCpy("stdLine"))

		if err != nil {
			return n, err
		}

		stdLine.textLineReader =
			strings.NewReader(strBuilder.String())

		if stdLine.textLineReader == nil {
			err = fmt.Errorf("%v\n"+
				"Error: strings.NewReader(formattedText)\n"+
				"returned a nil pointer.\n"+
				"stdLine.textLineReader == nil\n",
				ePrefix.String())

			return n, err
		}

		strBuilder.Reset()
	}

	n,
		err = new(textSpecificationAtom).
		readBytes(
			stdLine.textLineReader,
			p,
			ePrefix.XCpy(
				"p -> stdLine.textLineReader"))

	if err == io.EOF {

		stdLine.textLineReader = nil

	}

	return n, err
}

