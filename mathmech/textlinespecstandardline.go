//	     parameter 'errorPrefix' will be inserted or prefixed at
//	     the beginning of the error message.
func (stdLine *TextLineSpecStandardLine) InsertTextField(
	iTextField ITextFieldSpecification,
	indexId int,
	errorPrefix interface{}) (
	lastIndexId int,
	err error) {

	if stdLine.lock == nil {
		stdLine.lock = new(sync.Mutex)
	}

	stdLine.lock.Lock()

	defer stdLine.lock.Unlock()

	var ePrefix *ePref.ErrPrefixDto

	lastIndexId = -1

	ePrefix,
		err = ePref.ErrPrefixDto{}.NewIEmpty(
		errorPrefix,
		"TextLineSpecStandardLine."+
			"InsertTextField()",
		"")

	if err != nil {
		return lastIndexId, err
	}

	lastIndexId,
		err = new(textLineSpecStandardLineNanobot).
		insertTextFieldAtIndex(
			stdLine,
			iTextField,
			indexId,
			ePrefix.XCpy(
				fmt.Sprintf("stdLine.textFields[%v]<-iTextField",
					indexId)))

	if err != nil {
		lastIndexId = -1
	} else {
		lastIndexId--
	}

	return lastIndexId, err
}

